from mask import mask

assert mask("주민번호 900101-1234567 입니다") == "주민번호 [삭제] 입니다"
assert mask("9001011234567") == "[삭제]"
assert mask("900101 - 1234567") == "[삭제]"
assert mask("연락처 010-1234-5678") == "연락처 [삭제]"
assert mask("01012345678") == "[삭제]"
assert mask("010 1234 5678") == "[삭제]"
assert mask("011-123-4567") == "[삭제]"
for keep in ["02-3446-9927", "031-123-4567", "044-202-1234", "1522-1234", "1588-0000",
             "1339", "02-860-2441", "2024.2.26.~2025.2.28", "사업자 123-45-67890", "35만원 2,564,238원"]:
    assert mask(keep) == keep, keep
print("ok")
