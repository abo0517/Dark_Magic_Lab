import re

# 주민등록번호: 생년월일 6자리 + (하이픈/공백 가능) + 성별 1~8로 시작하는 7자리
RRN = re.compile(r"(?<!\d)\d{2}(?:0[1-9]|1[0-2])(?:0[1-9]|[12]\d|3[01])\s*[-–—~]?\s*[1-8]\d{6}(?!\d)")
# 휴대전화: 01x로 시작하는 10~11자리(구분자 가능)
MOBILE = re.compile(r"(?<!\d)01[016789][-.\s]?\d{3,4}[-.\s]?\d{4}(?!\d)")


def mask(text: str) -> str:
    return MOBILE.sub("[삭제]", RRN.sub("[삭제]", text))
