def mascot():
    # 걷는 강아지 스프라이트(4프레임) 중 첫 프레임만 잘라 쓴다
    im = PILImage.open(ROOT / "FE" / "bokgil-retriever-walk-v001.png").convert("RGBA")
    frame = im.crop((0, 0, im.width // 4, im.height))
    buf = io.BytesIO()
    frame.save(buf, "PNG")
    buf.seek(0)
    return Image(buf, width=27 * mm, height=36 * mm)


